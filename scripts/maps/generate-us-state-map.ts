async function generate() {
  const topoPath = path.resolve('node_modules/us-atlas/states-albers-10m.json');
  if (!fs.existsSync(topoPath)) {
    throw new Error('us-atlas package not found at ' + topoPath);
  }

  const topology = JSON.parse(fs.readFileSync(topoPath, 'utf8'));
  // Convert topology to GeoJSON FeatureCollection
  const statesGeo = topojson.feature(topology, topology.objects.states) as any;
  const pathGenerator = geoPath(); // Planar path generator since coordinates are pre-projected Albers

  const outputStates: Array<{
    fips: string;
    code: string;
    name: string;
    path: string;
    anchor: [number, number];
  }> = [];

  for (const feature of statesGeo.features) {
    const rawId = String(feature.id);
    const fips = rawId.padStart(2, '0');
    const info = FIPS_MAP[fips];
    if (!info) continue; // Filter to 50 states + DC

    const pathData = pathGenerator(feature);
    if (!pathData) continue;

    // Calculate default centroid
    const centroid = pathGenerator.centroid(feature);
    const roundX = Math.round(centroid[0] * 10) / 10;
    const roundY = Math.round(centroid[1] * 10) / 10;

    // Use manual anchor if reviewed, otherwise centroid
    const anchor = MANUAL_ANCHORS[info.code] || [roundX, roundY];

    outputStates.push({
      fips,
      code: info.code,
      name: info.name,
      path: pathData,
      anchor,
    });
  }

  // Sort states alphabetically by code
  outputStates.sort((a, b) => a.code.localeCompare(b.code));

  const targetDir = path.resolve('src/features/maps/generated');
  fs.mkdirSync(targetDir, { recursive: true });

  const generatedTs = `// AUTOGENERATED FILE - DO NOT EDIT MANUALLY
// Generated from us-atlas/states-albers-10m.json using scripts/maps/generate-us-state-map.ts
// Viewport: ${VIEW_BOX.width} x ${VIEW_BOX.height} (Albers USA pre-projected planar coordinates)
// Total States Plotted: ${outputStates.length}

export interface StateGeometryItem {
  fips: string;
  code: string;
  name: string;
  path: string;
  anchor: [number, number]; // [x, y] in viewBox
}

export const US_MAP_VIEWBOX = {
  width: ${VIEW_BOX.width},
  height: ${VIEW_BOX.height},
  aspectRatio: ${VIEW_BOX.width / VIEW_BOX.height},
  viewBoxString: "0 0 ${VIEW_BOX.width} ${VIEW_BOX.height}",
} as const;

export const US_STATES_GEOMETRY: StateGeometryItem[] = ${JSON.stringify(outputStates, null, 2)};

export const US_STATES_BY_CODE = new Map<string, StateGeometryItem>(
  US_STATES_GEOMETRY.map((s) => [s.code, s])
);
`;

  const outputPath = path.join(targetDir, 'usStateGeometry.ts');
  fs.writeFileSync(outputPath, generatedTs, 'utf8');

  console.log(`Successfully generated ${outputStates.length} US states geometry in ${outputPath}`);
  console.log(`File size: ${(fs.statSync(outputPath).size / 1024).toFixed(1)} KB`);
}

generate().catch((err) => {
  console.error('Generation failed:', err);
  process.exit(1);
});
